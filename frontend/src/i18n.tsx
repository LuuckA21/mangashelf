export type TranslationKey = keyof Messages

const STORAGE_KEY = 'mangashelf-language'

function browserLanguage(): Language {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'it' || saved === 'en') return saved
  } catch {
    // Storage can be disabled by strict privacy settings. The browser
    // preference remains a safe, deterministic fallback.
  }
  return navigator.language.toLowerCase().startsWith('it') ? 'it' : 'en'
}

interface I18nValue {
  language: Language
  locale: string
  t: (key: TranslationKey) => string
  setLanguage: (language: Language) => void
}

const I18nContext = createContext<I18nValue>({
  language: 'it',
  locale: 'it-CH',
  t: (key) => italian[key],
  setLanguage: () => undefined,
})

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(browserLanguage)

  const setLanguage = useCallback((language: Language) => {
    try {
      localStorage.setItem(STORAGE_KEY, language)
    } catch {
      // The account preference still persists server-side after login.
    }
    setLanguageState(language)
  }, [])

  useEffect(() => {
    document.documentElement.lang = language
  }, [language, setLanguage])

  const value = useMemo<I18nValue>(() => {
    const messages = language === 'it' ? italian : english
    return {
      language,
      locale: language === 'it' ? 'it-CH' : 'en-CH',
      t: (key) => messages[key],
      setLanguage,
    }
  }, [language])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n(): I18nValue {
  return useContext(I18nContext)
}
